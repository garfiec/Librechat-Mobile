#!/usr/bin/env python3
"""Generate the Kotlin copies of LibreChat's theme colour tables from the upstream submodule.

Reads, from upstream/ (the pinned LibreChat checkout):
  packages/data-provider/src/theme.ts            themeColorTokens, renamedThemeColorTokens
  packages/data-provider/src/themes/default.ts   the stock light palette
  packages/data-provider/src/themes/dark.ts      the stock dark palette
  packages/client/src/theme/themes/clickhouse.ts the bundled `clickhouse` palettes

and writes ThemeRole.kt and ClickHousePalette.kt under core/model's config/theme package.

  scripts/generate-theme-palettes.py           rewrite the Kotlin files
  scripts/generate-theme-palettes.py --check   exit 1 if they are out of date
  --upstream PATH reads another checkout of the pinned commit (a worktree's submodule may be empty).

Run it after /sync-upstream moves upstream/ (scripts/mirrors.json: theme-color-tokens,
theme-renamed-tokens, theme-stock-light, theme-stock-dark, theme-clickhouse-palette).
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UPSTREAM = ROOT / "upstream"
OUT_DIR = ROOT / "core/model/src/commonMain/kotlin/com/garfiec/librechat/core/model/config/theme"
PACKAGE = "com.garfiec.librechat.core.model.config.theme"

TOKEN = re.compile(r"'(rgb-[a-z0-9-]+)'")
ENTRY = re.compile(r"^\s*'(rgb-[a-z0-9-]+)':\s*'(\d{1,3}) (\d{1,3}) (\d{1,3})',")


def read(rel: str) -> str:
    return (UPSTREAM / rel).read_text()


def block(source: str, start: str, end: str) -> str:
    begin = source.index(start)
    return source[begin:source.index(end, begin)]


def token_list(theme_ts: str) -> list[str]:
    tokens = TOKEN.findall(block(theme_ts, "export const themeColorTokens", "] as const);"))
    if len(tokens) != len(set(tokens)):
        sys.exit("themeColorTokens has duplicates")
    return tokens


def renamed(theme_ts: str) -> list[tuple[str, str]]:
    body = block(theme_ts, "export const renamedThemeColorTokens", ";")
    return re.findall(r"\['(rgb-[a-z0-9-]+)',\s*'(rgb-[a-z0-9-]+)'\]", body)


def palette(source: str, start: str, tokens: list[str], label: str) -> dict[str, int]:
    values: dict[str, int] = {}
    for line in block(source, start, "\n};").splitlines():
        match = ENTRY.match(line)
        if match:
            r, g, b = (int(c) for c in match.groups()[1:])
            if max(r, g, b) > 255:
                sys.exit(f"{label}: {match.group(1)} has a channel above 255")
            values[match.group(1)] = (r << 16) | (g << 8) | b
    missing = [t for t in tokens if t not in values]
    extra = [t for t in values if t not in tokens]
    if missing or extra:
        sys.exit(f"{label}: missing {missing}, unknown {extra}")
    return values


def constant(token: str) -> str:
    return token.removeprefix("rgb-").replace("-", "_").upper()


def hex6(value: int) -> str:
    return f"0x{value:06X}"


def upstream_commit() -> str:
    return subprocess.run(
        ["git", "-C", str(UPSTREAM), "rev-parse", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()


HEADER = """// Generated by scripts/generate-theme-palettes.py from upstream LibreChat {commit}.
// Do not edit by hand: rerun the script.
package {package}
"""


def theme_role_kt(tokens, renames, light, dark, commit) -> str:
    rows = "\n".join(
        f'    {constant(t)}("{t}", {hex6(light[t])}, {hex6(dark[t])}),' for t in tokens
    )
    rename_rows = "\n".join(f'            "{old}" to {constant(new)},' for old, new in renames)
    return HEADER.format(commit=commit, package=PACKAGE) + f"""
/**
 * Every colour role a LibreChat theme paints (`themeColorTokens` in upstream
 * `packages/data-provider/src/theme.ts`), in upstream order, with the stock palette's 24-bit RGB
 * value in light ([libreChatLight], `themes/default.ts`) and dark ([libreChatDark], `themes/dark.ts`).
 */
enum class ThemeRole(val token: String, val libreChatLight: Int, val libreChatDark: Int) {{
{rows}
    ;

    companion object {{
        private val byToken: Map<String, ThemeRole> = entries.associateBy {{ it.token }}

        /** Role names a release shipped and a later one renamed, each with the role it is now. */
        val RENAMED: Map<String, ThemeRole> = mapOf(
{rename_rows}
        )

        fun of(token: String): ThemeRole? = byToken[token]
    }}
}}
"""


def appearance_keys() -> list[str]:
    """The `appearance` keys the app reads: the keys of the enums in ServerThemeAppearance.kt."""
    source = (OUT_DIR / "ServerThemeAppearance.kt").read_text()
    return re.findall(r'^\s+[A-Z0-9_]+\("([A-Za-z0-9]+)"\),?$', source, re.M)


def shape(source: str, keys: list[str]) -> dict[str, str]:
    """`clickHouseShape`'s string values for the [keys] it names, in the order the app lists them."""
    body = block(source, "const clickHouseShape = {", "\n};")
    values = {}
    for key, single, double in re.findall(r"^\s+(\w+):\s*(?:'((?:[^'\\]|\\.)*)'|\"([^\"]*)\")", body, re.M):
        values[key] = (single.replace("\\'", "'") if single else double)
    return {k: values[k] for k in keys if k in values}


def kotlin_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def clickhouse_kt(tokens, light, dark, appearance, commit) -> str:
    def rows(values):
        return "\n".join(f"        ThemeRole.{constant(t)} to {hex6(values[t])}," for t in tokens)

    def shape_row(key: str, value: str) -> str:
        if len(value) <= 70:
            return f"        {kotlin_string(key)} to {kotlin_string(value)},"
        # A long font stack, one family per line, so no line runs past the style limit.
        parts = [p.strip() for p in value.split(",")]
        joined = ",\n".join(f"            {kotlin_string(p)}" for p in parts)
        return f"        {kotlin_string(key)} to listOf(\n{joined},\n        ).joinToString(\", \"),"

    shape_rows = "\n".join(shape_row(k, v) for k, v in appearance.items())

    return HEADER.format(commit=commit, package=PACKAGE) + f"""
/**
 * The bundled `clickhouse` theme's colours (upstream `packages/client/src/theme/themes/clickhouse.ts`),
 * 24-bit RGB. Both modes name every role, so nothing falls back to the stock palette.
 */
internal object ClickHousePalette {{
    val light: Map<ThemeRole, Int> = mapOf(
{rows(light)}
    )

    val dark: Map<ThemeRole, Int> = mapOf(
{rows(dark)}
    )

    /** Both modes' `appearance` (`clickHouseShape`), as written, for the keys the app reads. */
    val appearance: Map<String, String> = mapOf(
{shape_rows}
    )
}}
"""


def main() -> None:
    global UPSTREAM
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if the generated files are stale")
    parser.add_argument("--upstream", type=Path, default=ROOT / "upstream",
                        help="LibreChat checkout to read (default: the upstream/ submodule)")
    args = parser.parse_args()
    UPSTREAM = args.upstream.resolve()
    pinned = re.search(r"^commit=(\w+)", (ROOT / "UPSTREAM_VERSION").read_text(), re.M).group(1)
    if upstream_commit() != pinned:
        sys.exit(f"{UPSTREAM} is at {upstream_commit()}, not the pinned {pinned} (UPSTREAM_VERSION)")

    theme_ts = read("packages/data-provider/src/theme.ts")
    tokens = token_list(theme_ts)
    renames = renamed(theme_ts)
    stock_light = palette(read("packages/data-provider/src/themes/default.ts"),
                          "export const defaultTheme", tokens, "default.ts")
    stock_dark = palette(read("packages/data-provider/src/themes/dark.ts"),
                         "export const darkTheme", tokens, "dark.ts")
    clickhouse = read("packages/client/src/theme/themes/clickhouse.ts")
    ch_light = palette(clickhouse, "export const clickHouseLightTheme", tokens, "clickhouse light")
    ch_dark = palette(clickhouse, "export const clickHouseDarkTheme", tokens, "clickhouse dark")
    ch_shape = shape(clickhouse, appearance_keys())
    commit = upstream_commit()

    outputs = {
        OUT_DIR / "ThemeRole.kt": theme_role_kt(tokens, renames, stock_light, stock_dark, commit),
        OUT_DIR / "ClickHousePalette.kt": clickhouse_kt(tokens, ch_light, ch_dark, ch_shape, commit),
    }
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
    if args.check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}")
        sys.exit(1 if stale else 0)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for path in stale:
        path.write_text(outputs[path])
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
